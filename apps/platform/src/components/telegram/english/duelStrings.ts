const dictionaries = { en, ru, uz } as const;

export type TgDuelKey = DuelKey;

export const useTgDuelT = () => {
  const { locale } = useTgEnglishT();
  const t = useCallback((key: DuelKey, params?: Record<string, string | number>) => {
    const template: string = dictionaries[locale][key] ?? en[key];
    return params ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? '')) : template;
  }, [locale]);
  return { t, locale };
};

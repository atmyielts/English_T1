#!/usr/bin/env node
// Generate the SAT Practice Algebra + Advanced Math content migration from the
// contract-A source JSON (content/sat-practice/{algebra,advanced_math}.json).
//
//   node scripts/content/sat-math-a.mjs           # (re)write the migration
//   node scripts/content/sat-math-a.mjs --check   # exit 1 if the migration is stale
//
// Output is deterministic: same JSON in, byte-identical SQL out. Ids follow
// contract A: parts md5('schood-sat-part:' || domain)::uuid, content units
// md5('schood-sat-q:' || slug)::uuid. Every insert is "on conflict do nothing",
// so re-running never overwrites a row a learner may already have answered.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATION = 'supabase/migrations/20261026140900_sat_practice_algebra_advanced_math.sql';
const PRODUCT_ID = '2cf7b1a7-4df9-4de8-99e8-5b9d5bb85010';
const EXPERIENCE_ID = 'd2f60197-eaa3-5772-88ac-b05d60f11bb5';
const MATH_SECTION_ID = 'bee41358-7368-5bbb-bb76-e42afe3c1c44';
const DOMAINS = [
  { domain: 'algebra', name: 'Algebra', displayOrder: 10, file: 'content/sat-practice/algebra.json' },
  { domain: 'advanced_math', name: 'Advanced Math', displayOrder: 11, file: 'content/sat-practice/advanced_math.json' },
];
const REVISION = 'original-2026-10-v2';
const SOURCE = 'original-schood-practice-v2';

const md5uuid = (text) => {
  const h = createHash('md5').update(text, 'utf8').digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
};
const lit = (text) => `'${String(text).replace(/'/g, "''")}'`;
const jsonb = (value) => `${lit(JSON.stringify(value))}::jsonb`;

function fail(message) {
  console.error(`sat-math-a: ${message}`);
  process.exit(1);
}

function unitRows(spec) {
  const items = JSON.parse(readFileSync(path.join(root, spec.file), 'utf8'));
  if (!Array.isArray(items) || items.length === 0) fail(`${spec.file} must be a non-empty array`);
  return items.map((q, index) => {
    if (q.official_domain !== spec.domain || q.section !== 'math') fail(`${q.slug}: wrong domain/section for ${spec.file}`);
    if (q.format !== 'mcq' && q.format !== 'spr') fail(`${q.slug}: format must be mcq or spr`);
    const data = { prompt: q.prompt };
    if (q.passage !== undefined) data.passage = q.passage;
    if (q.table !== undefined) data.table = q.table;
    if (q.figure_svg !== undefined) data.figure_svg = q.figure_svg;
    if (q.format === 'mcq') data.options = q.options;
    const metadata = {
      section_type: 'math',
      sat_domain: q.sat_domain,
      sat_official_domain: q.official_domain,
      sat_skill: q.skill,
      difficulty: q.difficulty,
      difficulty_basis: 'editorial',
      content_status: 'published',
      content_revision: REVISION,
      original_slug: q.slug,
      answer_format: q.format,
    };
    const correct = q.format === 'mcq' ? { option_id: q.answer } : { accepted: q.answer };
    const keyMetadata = { feedback: { explanation: q.explanation }, source: SOURCE };
    return {
      slug: q.slug,
      id: md5uuid(`schood-sat-q:${q.slug}`),
      type: q.format === 'mcq' ? 'question_single_choice' : 'question_spr',
      data, metadata, correct, keyMetadata,
      displayOrder: index + 1,
    };
  });
}

function build() {
  const seen = new Set();
  const out = [
    'begin;',
    "set local lock_timeout='5s';",
    "set local statement_timeout='30s';",
    '',
    '-- Original SAT Practice questions: Algebra and Advanced Math (contract A, revision original-2026-10-v2).',
    '-- Generated by scripts/content/sat-math-a.mjs from content/sat-practice/{algebra,advanced_math}.json. Do not edit by hand.',
    '-- Editorial difficulty tiers only, no official or calibrated claim. Every answer and distractor was verified by computation.',
    '-- Requires the sat-engine release (question_spr grading + KaTeX rendering) to be live before this content is published.',
    '-- Insert fresh identities only, never overwrite content already used by a learner.',
    '',
    `do $$ begin if not exists(select 1 from public.products where id='${PRODUCT_ID}') then raise exception 'SAT Practice product missing'; end if; end $$;`,
    `do $$ begin if not exists(select 1 from public.sections where id='${MATH_SECTION_ID}' and experience_id='${EXPERIENCE_ID}') then raise exception 'SAT Practice Math section missing'; end if; end $$;`,
  ];
  for (const spec of DOMAINS) {
    const partId = md5uuid(`schood-sat-part:${spec.domain}`);
    const rows = unitRows(spec);
    out.push('');
    out.push(`-- ${spec.name}: ${rows.length} questions.`);
    out.push(`do $$ begin if md5('schood-sat-part:${spec.domain}')::uuid <> '${partId}'::uuid then raise exception 'part id derivation mismatch'; end if; end $$;`);
    out.push(`insert into public.parts(id,section_id,name,display_order) values('${partId}','${MATH_SECTION_ID}',${lit(spec.name)},${spec.displayOrder}) on conflict do nothing;`);
    for (const r of rows) {
      if (seen.has(r.slug)) fail(`duplicate slug ${r.slug}`);
      seen.add(r.slug);
      out.push('');
      out.push(`insert into public.content_units(id,part_id,type,data,display_order,metadata) values('${r.id}','${partId}','${r.type}',${jsonb(r.data)},${r.displayOrder},${jsonb(r.metadata)}) on conflict do nothing;`);
      out.push(`insert into public.answer_keys(content_unit_id,correct,metadata) select '${r.id}',${jsonb(r.correct)},${jsonb(r.keyMetadata)} where exists(select 1 from public.content_units where id='${r.id}') on conflict do nothing;`);
    }
  }
  out.push('');
  out.push(`do $$ declare n integer; begin select count(*) into n from public.content_units u join public.parts p on p.id=u.part_id where p.section_id='${MATH_SECTION_ID}' and u.metadata->>'content_revision'='${REVISION}' and u.metadata->>'sat_official_domain' in ('algebra','advanced_math'); raise notice 'SAT Practice Algebra/Advanced Math questions present: % of ${seen.size}', n; end $$;`);
  out.push('');
  out.push('commit;');
  out.push('');
  return out.join('\n');
}

const sql = build();
const target = path.join(root, MIGRATION);
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== sql) fail(`${MIGRATION} is stale; run node scripts/content/sat-math-a.mjs`);
  console.log(`${MIGRATION} is up to date (${seen_count(sql)} questions).`);
} else {
  writeFileSync(target, sql, 'utf8');
  console.log(`wrote ${MIGRATION} (${Buffer.byteLength(sql)} bytes, ${seen_count(sql)} questions)`);
}

function seen_count(text) {
  return (text.match(/^insert into public\.content_units/gm) || []).length;
}

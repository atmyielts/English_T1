#!/usr/bin/env node
// Generates the SAT Practice Reading and Writing content migrations owned by agent sat-rw-a
// (Information and Ideas, Craft and Structure) from content/sat-practice/*.json.
//
//   node scripts/content/sat-rw-a.mjs          write the migrations
//   node scripts/content/sat-rw-a.mjs --check  exit 1 if the committed migrations are stale
//
// Deterministic: same JSON in, byte-identical SQL out. No dependencies.
// Ids follow contract A: parts md5('schood-sat-part:' || official_domain)::uuid,
// content units md5('schood-sat-q:' || slug)::uuid (computed here as literals).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const PRODUCT_ID = '2cf7b1a7-4df9-4de8-99e8-5b9d5bb85010';
const EXPERIENCE_ID = 'd2f60197-eaa3-5772-88ac-b05d60f11bb5';
const RW_SECTION_ID = '2dd5a6ad-d4e5-5141-982e-22469816765f';
const REVISION = 'original-2026-10-v2';
const SOURCE = 'original-schood-practice-v2';
const LEGACY = { information_and_ideas: 'command_of_evidence', craft_and_structure: 'vocabulary_in_context' };

const DOMAINS = [
  { domain: 'information_and_ideas', name: 'Information and Ideas', order: 10,
    json: 'content/sat-practice/information_and_ideas.json',
    migration: 'supabase/migrations/20261026142000_sat_practice_information_ideas.sql' },
  { domain: 'craft_and_structure', name: 'Craft and Structure', order: 11,
    json: 'content/sat-practice/craft_and_structure.json',
    migration: 'supabase/migrations/20261026142100_sat_practice_craft_structure.sql' },
];

const md5uuid = (text) => {
  const h = createHash('md5').update(text, 'utf8').digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
};
const lit = (value) => `'${String(value).replace(/'/g, "''")}'`;
const jsonb = (value) => `${lit(JSON.stringify(value))}::jsonb`;

function build({ domain, name, order, json }) {
  const items = JSON.parse(readFileSync(path.join(root, json), 'utf8'));
  if (!Array.isArray(items) || items.length === 0) throw new Error(`${json}: expected a non-empty array`);
  const partId = md5uuid(`schood-sat-part:${domain}`);
  const seen = new Set();
  const lines = [
    'begin;',
    "set local lock_timeout='5s';",
    "set local statement_timeout='30s';",
    '',
    `-- SAT Practice: ${items.length} original ${name} questions (Reading and Writing).`,
    `-- Generated by scripts/content/sat-rw-a.mjs from ${json}; do not edit by hand.`,
    '-- Original Schood items; editorial difficulty only, not calibrated or endorsed by College Board.',
    '-- Additive and idempotent: every insert skips rows that already exist (any unique violation).',
    '',
    `do $$ begin if not exists(select 1 from public.sections s join public.experiences e on e.id=s.experience_id where s.id='${RW_SECTION_ID}' and e.id='${EXPERIENCE_ID}' and e.product_id='${PRODUCT_ID}') then raise exception 'SAT Practice Reading and Writing section missing'; end if; end $$;`,
    '',
    `insert into public.parts(id,section_id,name,display_order,metadata) values('${partId}','${RW_SECTION_ID}',${lit(name)},${order},${jsonb({ sat_official_domain: domain, content_revision: REVISION })}) on conflict do nothing;`,
    '',
  ];
  items.forEach((item, index) => {
    if (item.official_domain !== domain) throw new Error(`${item.slug}: official_domain ${item.official_domain} does not belong in ${json}`);
    if (item.section !== 'reading_writing' || item.format !== 'mcq') throw new Error(`${item.slug}: expected reading_writing mcq`);
    if (seen.has(item.slug)) throw new Error(`${item.slug}: duplicate slug`);
    seen.add(item.slug);
    const ids = (item.options ?? []).map((option) => option.id).join('');
    if (ids !== 'ABCD' || !['A', 'B', 'C', 'D'].includes(item.answer)) throw new Error(`${item.slug}: options must be A-D and answer one of them`);
    if (item.sat_domain !== LEGACY[domain]) throw new Error(`${item.slug}: sat_domain must be ${LEGACY[domain]}`);
    const id = md5uuid(`schood-sat-q:${item.slug}`);
    const data = { prompt: item.prompt };
    if (item.passage) data.passage = item.passage;
    if (item.table) data.table = item.table;
    if (item.figure_svg) data.figure_svg = item.figure_svg;
    data.options = item.options;
    const metadata = {
      section_type: 'reading_writing',
      sat_domain: item.sat_domain,
      sat_official_domain: domain,
      sat_skill: item.skill,
      difficulty: item.difficulty,
      difficulty_basis: 'editorial',
      content_status: 'published',
      content_revision: REVISION,
      original_slug: item.slug,
      answer_format: 'mcq',
    };
    lines.push(`insert into public.content_units(id,part_id,type,data,display_order,metadata) values('${id}','${partId}','question_single_choice',${jsonb(data)},${index + 1},${jsonb(metadata)}) on conflict do nothing;`);
    lines.push(`insert into public.answer_keys(content_unit_id,correct,metadata) values('${id}',${jsonb({ option_id: item.answer })},${jsonb({ feedback: { explanation: item.explanation }, source: SOURCE })}) on conflict do nothing;`);
    lines.push('');
  });
  lines.push('notify pgrst,\'reload schema\';', '', 'commit;', '');
  return lines.join('\n');
}

const check = process.argv.includes('--check');
let stale = 0;
for (const spec of DOMAINS) {
  const sql = build(spec);
  const target = path.join(root, spec.migration);
  if (Buffer.byteLength(sql) > 2_000_000) throw new Error(`${spec.migration} exceeds 2 MB; split it`);
  if (check) {
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== sql) { console.error(`stale: ${spec.migration}`); stale += 1; }
  } else {
    writeFileSync(target, sql);
    console.log(`wrote ${spec.migration} (${Buffer.byteLength(sql)} bytes)`);
  }
}
process.exit(stale ? 1 : 0);

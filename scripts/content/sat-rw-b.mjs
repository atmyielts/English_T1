#!/usr/bin/env node
// Generate the SAT Practice Expression of Ideas + Standard English Conventions
// content migration from the contract-A source JSON (agent sat-rw-b).
//
//   node scripts/content/sat-rw-b.mjs          # write the migration
//   node scripts/content/sat-rw-b.mjs --check  # exit 1 if the committed migration is stale
//
// Deterministic: ids are md5-derived exactly as Postgres md5(text)::uuid would
// produce them, rows keep JSON order, and no timestamps are embedded.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCES = ['content/sat-practice/expression_of_ideas.json', 'content/sat-practice/standard_english_conventions.json'];
const MIGRATION = 'supabase/migrations/20261026143000_sat_practice_expression_conventions.sql';
const RW_SECTION = '2dd5a6ad-d4e5-5141-982e-22469816765f';
const PARTS = {
  expression_of_ideas: { name: 'Expression of Ideas', order: 12 },
  standard_english_conventions: { name: 'Standard English Conventions', order: 13 },
};
const REVISION = 'original-2026-10-v2';

const md5uuid = (text) => {
  const h = createHash('md5').update(text, 'utf8').digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
};
const lit = (value) => `'${String(value).replaceAll("'", "''")}'`;
const jsonb = (value) => `${lit(JSON.stringify(value))}::jsonb`;

const raw = SOURCES.map((file) => readFileSync(file, 'utf8'));
const sha = createHash('sha256').update(raw.join('\n')).digest('hex');
const items = raw.flatMap((text) => JSON.parse(text));

const slugs = new Set();
for (const item of items) {
  if (slugs.has(item.slug)) throw new Error(`duplicate slug ${item.slug}`);
  slugs.add(item.slug);
  if (!PARTS[item.official_domain]) throw new Error(`${item.slug}: domain ${item.official_domain} is not owned by sat-rw-b`);
  if (item.format !== 'mcq' || !Array.isArray(item.options) || item.options.length !== 4) throw new Error(`${item.slug}: expected a 4-option mcq`);
}

const lines = [
  'begin;',
  "set local lock_timeout='5s';",
  "set local statement_timeout='60s';",
  '',
  '-- Original SAT Practice Reading and Writing questions (agent sat-rw-b):',
  `-- ${items.filter((i) => i.official_domain === 'expression_of_ideas').length} Expression of Ideas + ${items.filter((i) => i.official_domain === 'standard_english_conventions').length} Standard English Conventions.`,
  '-- Editorial difficulty tiers; no official or calibrated-mock claim.',
  `-- Generated by scripts/content/sat-rw-b.mjs from ${SOURCES.join(', ')} (sha256 ${sha}). Do not edit by hand.`,
  '-- Insert-only and idempotent: existing rows (and any unique-constraint clash) are skipped, never overwritten.',
  '',
  `do $$ begin if not exists(select 1 from public.sections where id='${RW_SECTION}') then raise exception 'SAT Practice Reading and Writing section missing'; end if; end $$;`,
  '',
];

for (const [domain, part] of Object.entries(PARTS)) {
  const partId = md5uuid(`schood-sat-part:${domain}`);
  lines.push(`insert into public.parts(id,section_id,name,display_order) values('${partId}','${RW_SECTION}',${lit(part.name)},${part.order}) on conflict do nothing;`, '');
  items.filter((item) => item.official_domain === domain).forEach((item, index) => {
    const id = md5uuid(`schood-sat-q:${item.slug}`);
    const data = { prompt: item.prompt };
    if (item.passage) data.passage = item.passage;
    if (item.table) data.table = item.table;
    if (item.figure_svg) data.figure_svg = item.figure_svg;
    data.options = item.options;
    const metadata = {
      section_type: item.section, sat_domain: item.sat_domain, sat_official_domain: item.official_domain, sat_skill: item.skill,
      difficulty: item.difficulty, difficulty_basis: 'editorial', content_status: 'published', content_revision: REVISION,
      original_slug: item.slug, answer_format: item.format,
    };
    lines.push(`insert into public.content_units(id,part_id,type,data,display_order,metadata) values('${id}','${partId}','question_single_choice',${jsonb(data)},${index + 1},${jsonb(metadata)}) on conflict do nothing;`);
    lines.push(`insert into public.answer_keys(content_unit_id,correct,metadata) select '${id}',${jsonb({ option_id: item.answer })},${jsonb({ feedback: { explanation: item.explanation }, source: 'original-schood-practice-v2' })} where exists(select 1 from public.content_units where id='${id}') on conflict do nothing;`);
    lines.push('');
  });
}
lines.push('commit;', '');
const sql = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = readFileSync(MIGRATION, 'utf8');
  if (current !== sql) { console.error(`${MIGRATION} is stale; rerun node scripts/content/sat-rw-b.mjs`); process.exit(1); }
  console.log(`${MIGRATION} is up to date (${items.length} items).`);
} else {
  writeFileSync(MIGRATION, sql);
  console.log(`Wrote ${MIGRATION}: ${items.length} items, ${(Buffer.byteLength(sql) / 1024).toFixed(0)} KB.`);
}

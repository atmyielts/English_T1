#!/usr/bin/env node
// Generates the IELTS Playbook premium "Advanced Lab" migration from
// content/ielts-playbook/premium-guides/*.json.
//
//   node scripts/content/ielts-playbook-premium.mjs          # write the migration
//   node scripts/content/ielts-playbook-premium.mjs --check  # fail if it is stale
//
// Safety rules baked into the SQL:
// - sections are only ever INSERTed (`on conflict (id) do nothing`); nothing an
//   admin authored in production is updated or deleted;
// - ids are deterministic: md5('schood-ielts-pb-section:' || slug || ':' || n)::uuid;
// - new sections are appended after the page's existing sections
//   (base = current max sort_order of the sections that are not ours).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', '..');
const sourceDir = path.join(root, 'content', 'ielts-playbook', 'premium-guides');
const migrationName = '20261026120100_ielts_playbook_premium_advanced_labs';
const target = path.join(root, 'supabase', 'migrations', `${migrationName}.sql`);
const BLOCK_TYPES = new Set(['rich_text', 'checklist', 'faq', 'callout']);
const ORDER = [
  'guide-listening-traps-premium',
  'guide-reading-paraphrase-premium',
  'guide-writing-task-2-premium',
  'guide-speaking-band-7-premium',
  'guide-band-6-to-7-roadmap',
  'guide-retake-decision-premium',
];
const TAG = '$ipb$';

const words = (value) => {
  if (typeof value === 'string') return value.split(/\s+/).filter(Boolean).length;
  if (Array.isArray(value)) return value.reduce((sum, item) => sum + words(item), 0);
  if (value && typeof value === 'object') return Object.values(value).reduce((sum, item) => sum + words(item), 0);
  return 0;
};

const quote = (text) => {
  if (text.includes(TAG)) throw new Error(`Content contains the dollar-quote tag ${TAG}`);
  return `${TAG}${text}${TAG}`;
};

const guides = ORDER.map((slug) => {
  const file = path.join(sourceDir, `${slug}.json`);
  const guide = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (guide.slug !== slug) throw new Error(`${file}: slug mismatch`);
  const headings = new Set();
  guide.sections.forEach((section, index) => {
    if (!BLOCK_TYPES.has(section.block_type)) throw new Error(`${slug}#${index + 1}: block_type ${section.block_type}`);
    if (!section.heading?.trim()) throw new Error(`${slug}#${index + 1}: missing heading`);
    if (headings.has(section.heading)) throw new Error(`${slug}: duplicate heading ${section.heading}`);
    headings.add(section.heading);
  });
  const contentWords = guide.sections.reduce((sum, section) => sum + words(section.content), 0);
  if (guide.sections.length < 20) throw new Error(`${slug}: needs 20+ sections`);
  if (contentWords < 3000) throw new Error(`${slug}: needs 3,000+ words (has ${contentWords})`);
  return { slug, sections: guide.sections, contentWords };
});

const ids = (slug, count) =>
  Array.from({ length: count }, (_, i) => `md5('schood-ielts-pb-section:${slug}:${i + 1}')::uuid`).join(', ');

const guideSql = ({ slug, sections, contentWords }) => {
  const values = sections
    .map((section, index) =>
      `    (${index + 1}, '${section.block_type}', ${quote(section.heading.trim())}, ${quote(JSON.stringify(section.content))}::jsonb)`)
    .join(',\n');
  return `-- ${slug}: ${sections.length} sections, ${contentWords.toLocaleString('en-GB')} words
with target as (
  select
    p.id as page_id,
    coalesce((
      select max(s.sort_order)
      from public.ielts_playbook_page_sections s
      where s.page_id = p.id
        and s.id <> all (array[${ids(slug, sections.length)}])
    ), 0) as base_order
  from public.ielts_playbook_pages p
  where p.locale_code = 'en'
    and p.slug = '${slug}'
),
seed(n, block_type, heading, content) as (
  values
${values}
)
insert into public.ielts_playbook_page_sections (id, page_id, block_type, heading, status, sort_order, content, metadata)
select
  md5('schood-ielts-pb-section:' || '${slug}' || ':' || seed.n)::uuid,
  target.page_id,
  seed.block_type,
  seed.heading,
  'published',
  target.base_order + seed.n,
  seed.content,
  jsonb_build_object(
    'seeded_by', '${migrationName}',
    'pack', 'advanced_lab',
    'content_revision', 'premium-advanced-lab-2026-10',
    'source_file', 'content/ielts-playbook/premium-guides/${slug}.json'
  )
from target
cross join seed
on conflict (id) do nothing;
`;
};

const totalWords = guides.reduce((sum, guide) => sum + guide.contentWords, 0);
const totalSections = guides.reduce((sum, guide) => sum + guide.sections.length, 0);
const sql = `-- ============================================================================
-- IELTS Playbook premium guides: "Advanced Lab" depth pack
-- ----------------------------------------------------------------------------
-- GENERATED by scripts/content/ielts-playbook-premium.mjs from
-- content/ielts-playbook/premium-guides/*.json. Do not edit by hand.
--
-- ${guides.length} guides, ${totalSections} new sections, ${totalWords.toLocaleString('en-GB')} words of original writing.
-- Insert-only and idempotent: existing (admin-authored) sections are never
-- updated or deleted; new sections are appended after them.
-- ============================================================================

begin;
set local lock_timeout = '5s';

${guides.map(guideSql).join('\n')}
commit;
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== sql) {
    console.error(`${path.relative(root, target)} is stale; run node scripts/content/ielts-playbook-premium.mjs`);
    process.exit(1);
  }
  console.log('premium advanced-lab migration is up to date');
} else {
  fs.writeFileSync(target, sql);
  for (const guide of guides) console.log(`${guide.slug}: ${guide.sections.length} sections, ${guide.contentWords} words`);
  console.log(`wrote ${path.relative(root, target)} (${(Buffer.byteLength(sql) / 1024).toFixed(0)} KB)`);
}

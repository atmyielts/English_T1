#!/usr/bin/env node
// Generates the SAT Practice content migration for Problem-Solving and Data Analysis and
// Geometry and Trigonometry (agent sat-math-b) from the reviewed source JSON.
//
//   node scripts/content/sat-math-b.mjs           write the migration(s)
//   node scripts/content/sat-math-b.mjs --check   exit 1 if the committed migration(s) differ
//
// Deterministic: ids are md5-derived (same as md5(text)::uuid in Postgres), items keep
// their source order, and JSON keys are emitted in a fixed order. Contract A of the
// 2026-10-24 SAT content push: one part per official domain under the Math section of the
// SAT Practice experience, content_units + answer_keys per item, all inserts
// `on conflict do nothing` so a re-run never overwrites rows a learner may have answered.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const PRODUCT = '2cf7b1a7-4df9-4de8-99e8-5b9d5bb85010';
const EXPERIENCE = 'd2f60197-eaa3-5772-88ac-b05d60f11bb5';
const MATH_SECTION = 'bee41358-7368-5bbb-bb76-e42afe3c1c44';
const REVISION = 'original-2026-10-v2';
const SOURCE = 'original-schood-practice-v2';
const DOMAINS = [
  { key: 'problem_solving_data_analysis', name: 'Problem-Solving and Data Analysis', order: 12, sat: 'problem_solving_data_analysis' },
  { key: 'geometry_trigonometry', name: 'Geometry and Trigonometry', order: 13, sat: 'geometry_trig' },
];
// Timestamps inside the sat-math-b range 20261026141000-20261026141999.
const FIRST_STAMP = 20261026141000;
const MAX_BYTES = 1_900_000;

const md5uuid = (text) => {
  const h = createHash('md5').update(text, 'utf8').digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
};
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const jsonb = (v) => `${q(JSON.stringify(v))}::jsonb`;

function loadItems(domain) {
  const file = path.join(ROOT, 'content', 'sat-practice', `${domain.key}.json`);
  const items = JSON.parse(readFileSync(file, 'utf8'));
  if (!Array.isArray(items)) throw new Error(`${file} must be an array`);
  for (const item of items) {
    if (item.official_domain !== domain.key || item.section !== 'math' || item.sat_domain !== domain.sat) {
      throw new Error(`${item.slug}: wrong domain mapping`);
    }
    if (item.format === 'mcq' && !(Array.isArray(item.options) && item.options.length === 4 && item.options.some((o) => o.id === item.answer))) {
      throw new Error(`${item.slug}: mcq answer must be one of four options`);
    }
    if (item.format === 'spr' && !(Array.isArray(item.answer) && item.answer.length > 0 && !item.options)) {
      throw new Error(`${item.slug}: spr needs accepted answers and no options`);
    }
  }
  return items;
}

function itemSql(item, partId, displayOrder) {
  const id = md5uuid(`schood-sat-q:${item.slug}`);
  const data = { prompt: item.prompt };
  if (item.passage) data.passage = item.passage;
  if (item.table) data.table = item.table;
  if (item.figure_svg) data.figure_svg = item.figure_svg;
  if (item.format === 'mcq') data.options = item.options.map((o) => ({ id: o.id, label: o.label }));
  const metadata = {
    section_type: 'math',
    sat_domain: item.sat_domain,
    sat_official_domain: item.official_domain,
    sat_skill: item.skill,
    difficulty: item.difficulty,
    difficulty_basis: 'editorial',
    content_status: 'published',
    content_revision: REVISION,
    original_slug: item.slug,
    answer_format: item.format,
  };
  const type = item.format === 'mcq' ? 'question_single_choice' : 'question_spr';
  const correct = item.format === 'mcq' ? { option_id: item.answer } : { accepted: item.answer };
  const keyMeta = { feedback: { explanation: item.explanation }, source: SOURCE };
  return `insert into public.content_units(id,part_id,type,data,display_order,metadata) values(${q(id)},${q(partId)},${q(type)},${jsonb(data)},${displayOrder},${jsonb(metadata)}) on conflict do nothing;\n\n` +
    `insert into public.answer_keys(content_unit_id,correct,metadata) values(${q(id)},${jsonb(correct)},${jsonb(keyMeta)}) on conflict do nothing;\n\n`;
}

function header(stamp, part, total) {
  return `begin;\nset local lock_timeout='5s';\nset local statement_timeout='30s';\n\n` +
    `-- Generated by scripts/content/sat-math-b.mjs from content/sat-practice/{problem_solving_data_analysis,geometry_trigonometry}.json.\n` +
    `-- Do not edit by hand; edit the JSON and regenerate.${total > 1 ? ` File ${part} of ${total}.` : ''}\n` +
    `-- Original Schood SAT Practice questions (${REVISION}); editorial difficulty, no official or calibrated claim.\n` +
    `-- Insert fresh identities only; never overwrite content a learner may already have answered.\n\n` +
    `do $$ begin\n  if not exists(select 1 from public.products where id=${q(PRODUCT)}) then raise exception 'SAT Practice product missing'; end if;\n` +
    `  if not exists(select 1 from public.sections where id=${q(MATH_SECTION)} and experience_id=${q(EXPERIENCE)}) then raise exception 'SAT Practice Math section missing'; end if;\nend $$;\n\n`;
}

export function build() {
  const blocks = [];
  for (const domain of DOMAINS) {
    const partId = md5uuid(`schood-sat-part:${domain.key}`);
    const partSql = `-- ${domain.name}: part id = md5('schood-sat-part:${domain.key}')::uuid\n` +
      `insert into public.parts(id,section_id,name,display_order,metadata) values(${q(partId)},${q(MATH_SECTION)},${q(domain.name)},${domain.order},${jsonb({ sat_official_domain: domain.key, content_revision: REVISION })}) on conflict do nothing;\n\n` +
      `do $$ begin if not exists(select 1 from public.parts where id=${q(partId)} and section_id=${q(MATH_SECTION)}) then raise exception 'SAT Practice part ${domain.key} could not be created (display_order ${domain.order} taken?)'; end if; end $$;\n\n`;
    blocks.push({ partSql, items: loadItems(domain).map((item, i) => itemSql(item, partId, i + 1)) });
  }
  // Pack into files under MAX_BYTES; each file re-asserts the parts it needs (idempotent).
  const files = [];
  let current = null;
  for (const block of blocks) {
    let needsPart = true;
    for (const sql of block.items) {
      if (!current || Buffer.byteLength(current.body + sql) > MAX_BYTES) {
        current = { body: '' };
        files.push(current);
        needsPart = true;
      }
      if (needsPart) { current.body += block.partSql; needsPart = false; }
      current.body += sql;
    }
  }
  return files.map((f, i) => ({
    name: `${FIRST_STAMP + i * 100}_sat_practice_data_geometry${files.length > 1 ? `_${i + 1}` : ''}.sql`,
    sql: header(FIRST_STAMP + i * 100, i + 1, files.length) + f.body + (i === files.length - 1 ? presence(blocks) : '') + 'commit;\n',
  }));
}

function presence(blocks) {
  const total = blocks.reduce((n, b) => n + b.items.length, 0);
  const parts = DOMAINS.map((d) => q(md5uuid(`schood-sat-part:${d.key}`))).join(',');
  return `do $$ declare n integer; begin\n  select count(*) into n from public.content_units u join public.answer_keys k on k.content_unit_id=u.id\n` +
    `    where u.part_id in (${parts}) and u.metadata->>'content_revision'=${q(REVISION)};\n` +
    `  raise notice 'SAT Practice Problem-Solving/Geometry questions present: % of ${total}', n;\nend $$;\n\n`;
}

const check = process.argv.includes('--check');
let stale = false;
for (const file of build()) {
  const target = path.join(ROOT, 'supabase', 'migrations', file.name);
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== file.sql) { console.error(`stale: ${file.name}`); stale = true; }
    else console.log(`up to date: ${file.name} (${Buffer.byteLength(file.sql)} bytes)`);
  } else {
    writeFileSync(target, file.sql);
    console.log(`wrote ${file.name} (${Buffer.byteLength(file.sql)} bytes)`);
  }
}
if (stale) process.exit(1);

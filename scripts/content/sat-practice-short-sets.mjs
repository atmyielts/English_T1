import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { isAbsolute, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toContentRows, validateItems } from '../../supabase/functions/_shared/sat-practice-content.ts';
import { SHORT_SETS, shortSetQuestionIds } from '../../supabase/functions/_shared/sat-practice-short-sets.ts';

const root = fileURLToPath(new URL('../../', import.meta.url));
const privateArg = process.argv.indexOf('--private-dir');
const privateDirectory = privateArg >= 0 ? process.argv[privateArg + 1] : undefined;
if (!privateDirectory || !isAbsolute(privateDirectory)) throw new Error('Provide an absolute --private-dir outside this worktree.');
const source = realpathSync(privateDirectory);
const withinCheckout = relative(realpathSync(root), source);
if (withinCheckout !== '..' && !withinCheckout.startsWith(`..${sep}`) && !isAbsolute(withinCheckout)) {
  throw new Error('Practice questions and answer keys must stay outside this worktree.');
}
const target = resolve(source, 'apply_sat_practice_short_sets.sql');
const experienceId = 'd2f60197-eaa3-5772-88ac-b05d60f11bb5';
const sections = {
  reading_writing: '2dd5a6ad-d4e5-5141-982e-22469816765f',
  math: 'bee41358-7368-5bbb-bb76-e42afe3c1c44',
};
const revision = 'sat-practice-short-sets-2026-11-v1';
const quote = value => `'${value.replaceAll("'", "''")}'`;
const json = value => `${quote(JSON.stringify(value))}::jsonb`;
const part = section => `md5('schood-sat-part:eight-week-short-sets:${section}')::uuid`;
const questions = SHORT_SETS.flatMap(set => {
  const items = JSON.parse(readFileSync(resolve(source, `${set.slug}.json`), 'utf8'));
  const ids = shortSetQuestionIds(set.slug);
  if (!Array.isArray(items) || items.length !== ids.length) throw new Error(`Invalid length in ${set.slug}`);
  return items.map((item, i) => {
    const number = String(i + 1).padStart(2, '0');
    if (item.slug !== `eight-week-${set.slug}-${number}`) throw new Error(`Wrong question slug in ${set.slug}`);
    return { item, id: ids[i] };
  });
});
const validation = validateItems(questions.map(row => row.item));
if (validation.errors.length || validation.warnings.length) throw new Error(JSON.stringify(validation));

const sql = [
  '-- Generated by scripts/content/sat-practice-short-sets.mjs.',
  'begin;',
  "set local lock_timeout='5s';",
  "set local statement_timeout='30s';",
  '',
];
for (const [section, sectionId] of Object.entries(sections)) {
  sql.push(`do $$ begin if not exists (select 1 from public.sections where id='${sectionId}' and experience_id='${experienceId}') then raise exception 'SAT Practice section missing'; end if; end $$;`);
  sql.push(`insert into public.parts(id,section_id,name,display_order) values (${part(section)},'${sectionId}','Short Sets',70) on conflict (id) do nothing;`, '');
}
for (const [index, { item, id }] of questions.entries()) {
  const q = toContentRows(item);
  const metadata = { ...q.metadata, content_revision: revision, sat_practice_short_set_only: true };
  sql.push(
    `insert into public.content_units(id,part_id,type,data,display_order,metadata) values ('${id}',${part(q.section)},'${q.type}',${json(q.data)},${index + 1},${json(metadata)}) on conflict (id) do nothing;`,
    `insert into public.answer_keys(content_unit_id,correct,metadata) values ('${id}',${json(q.correct)},${json(q.key_metadata)}) on conflict (content_unit_id) do nothing;`,
  );
}
const ids = questions.map(row => `'${row.id}'::uuid`).join(',');
sql.push('', `do $$ begin if (select count(*) from public.content_units u join public.answer_keys k on k.content_unit_id=u.id where u.id in (${ids}) and u.part_id in (${Object.keys(sections).map(part).join(',')}) and u.metadata->>'content_revision'='${revision}') <> ${questions.length} then raise exception 'SAT Practice Short Sets content is incomplete'; end if; end $$;`, '', 'commit;', '');
const migration = sql.join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== migration) throw new Error('Short Sets migration needs rebuilding');
} else {
  writeFileSync(target, migration);
}
console.log(`${SHORT_SETS.length} short sets and ${questions.length} questions verified`);

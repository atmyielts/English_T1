// C12 curriculum in a box: a whole multi-level course (for example General English
// A1-B2, or IELTS 5 to 7) planned as an outline, then generated one unit at a time
// as jobs (each one model call, well under the Edge time limit, with a heartbeat so
// an interrupted unit is retried), reviewed unit by unit by the centre's
// methodologist, and only then published: to the shared centre library, and to
// Academy Courses through Approve & run with the publisher's own Academy token.

const TRACKS = ['general', 'ielts', 'multilevel', 'exam_other', 'kids'] as const;
const STALE_MS = 5 * 60_000;
const outlineSchema = s.object({
  levels: s.array(s.object({ level: s.enumOf(CEFR_LEVELS), units: s.array(s.object({ title: s.string({ min: 3, max: 160 }), can_do: s.array(s.string({ min: 5, max: 200 }), { min: 1, max: 4 }) }), { min: 1, max: 12 }) }), { min: 1, max: 6 }),
});

interface Brief { levels: CefrLevel[]; units_per_level: number; lessons_per_unit: number; track: (typeof TRACKS)[number]; language: 'en' | 'uz' | 'ru'; minutes: number; notes: string | null }
const briefOf = (row: CurriculumRow) => row.brief as unknown as Brief;

const curriculumJson = (row: CurriculumRow, units: UnitRow[]) => ({
  id: row.id, title: row.title, brief: row.brief, status: row.status, published_at: row.published_at, created_at: row.created_at,
  progress: { total: units.length, ready: units.filter((u) => ['ready', 'approved'].includes(u.status)).length, approved: units.filter((u) => u.status === 'approved').length, failed: units.filter((u) => u.status === 'failed').length, generating: units.filter((u) => u.status === 'generating').length },
  units: units.sort((a, b) => a.position - b.position).map((u) => {
    const content = isUnitContent(u.content) ? u.content : null;
    return { id: u.id, position: u.position, level: u.level, title: u.title, status: u.status, review_notes: u.review_notes, content: content ? unitView(content) : null, page_ids: u.page_ids, verification: content?.problems ?? null };
  }),
  cost: { outline: quoteCredits('curriculum.outline').credits, per_unit: quoteCredits('curriculum.unit').credits },
});

export const curricula = {
  async GET(ctx: RequestContext) {
    const centre = await requireCentre(ctx, ['owner', 'admin', 'teacher']);
    const id = ctx.query.get('id');
    if (id) {
      const row = await centre.deps.store.table('curricula').get({ id: uuid(id, 'id'), workspace_id: centre.access.workspace.id });
      if (!row) throw new SchoodAIError('not_found', 'Curriculum not found.', 404);
      return { curriculum: curriculumJson(row, await centre.deps.store.table('units').list({ curriculum_id: row.id })) };
    }
    const rows = await centre.deps.store.table('curricula').list({ workspace_id: centre.access.workspace.id }, { order: 'created_at', desc: true, limit: 50 });
    const units = rows.length ? await centre.deps.store.table('units').list({ workspace_id: centre.access.workspace.id }, { in: { curriculum_id: rows.map((row) => row.id) } }) : [];
    return { curricula: rows.map((row) => ({ ...curriculumJson(row, units.filter((u) => u.curriculum_id === row.id)), units: undefined })) };
  },
  /** { title, levels, units_per_level, lessons_per_unit, track, language, minutes?, notes? }: plans the outline (charged), then units are generated by `curriculum-run`. */
  async POST(ctx: RequestContext) {
    const centre = await requireCentre(ctx, ['owner', 'admin']);
    await ctx.requireFeature('C12');
    const body = record(await ctx.body());
    const levels = stringList(body.levels, 'levels', { max: 6, pattern: /^(pre_a1|a1|a2|b1|b2|c1|c2)$/ }) as CefrLevel[];
    if (!levels.length) throw new SchoodAIError('invalid_request', 'Choose at least one level.', 400, { field: 'levels' });
    const brief: Brief = {
      levels: levels.sort((a, b) => CEFR_LEVELS.indexOf(a) - CEFR_LEVELS.indexOf(b)), units_per_level: integer(body.units_per_level, 'units_per_level', 1, 12),
      lessons_per_unit: integer(body.lessons_per_unit, 'lessons_per_unit', 1, 6), track: oneOf(body.track ?? 'general', 'track', TRACKS),
      language: oneOf(body.language ?? centre.access.workspace.houseStyle.instruction_language ?? 'en', 'language', ['en', 'uz', 'ru'] as const),
      minutes: body.minutes === undefined ? 90 : integer(body.minutes, 'minutes', 30, 180), notes: optionalText(body.notes, 'notes', { max: 1500 }),
    };
    const title = text(body.title, 'title', { max: 160 });
    const { result, credits } = await ctx.ai.charged({ key: 'curriculum.outline', mode: 'json', reference: ctx.idempotencyKey ? `curriculum-outline:${ctx.idempotencyKey}` : undefined }, (session) => session.json({
      schema: outlineSchema, maxTokens: 2500, temperature: 0.4,
      messages: [
        { role: 'system', content: centrePrompt({
          workspace: centre.access.workspace, locale: ctx.locale,
          task: `Plan a ${brief.track} English course for an education centre: for each level in the brief, exactly ${brief.units_per_level} units in a sensible order, each with a title and 1-4 CEFR-style can-do aims. Units build on each other across levels. Write titles and aims in English.`,
          blocks: [{ kind: 'brief', title: 'Course brief', data: { title, ...brief } }],
        }) },
        { role: 'user', content: brief.notes ? `Notes from the centre:\n${wrapUserMessage(brief.notes)}` : 'Plan the course.' },
      ],
    }));
    const ws = centre.access.workspace;
    const row = await centre.deps.store.table('curricula').insert({ workspace_id: ws.id, title, brief: brief as unknown as Record<string, unknown>, status: 'generating', outline: result as unknown as Record<string, unknown>, created_by: ctx.user.id });
    let position = 0;
    for (const level of brief.levels) {
      const planned = result.levels.find((entry) => entry.level === level)?.units ?? [];
      for (let index = 0; index < brief.units_per_level; index++) {
        const unit = planned[index] ?? { title: `${LEVEL_LABEL[level]} unit ${index + 1}`, can_do: [] };
        await centre.deps.store.table('units').insert({ curriculum_id: row.id, workspace_id: ws.id, position: ++position, level, title: unit.title.slice(0, 160), content: { planned_can_do: unit.can_do } });
      }
    }
    await ctx.audit('centre.curriculum_planned', { levels: brief.levels, units: position }, { type: 'curriculum', id: row.id });
    return { curriculum: curriculumJson(row, await centre.deps.store.table('units').list({ curriculum_id: row.id })), credits };
  },
};

/** POST centre/curriculum-run { id }: generates the next unit that needs it (one model call). Call again until none is left. */
export async function run(ctx: RequestContext) {
  const centre = await requireCentre(ctx, ['owner', 'admin']);
  await ctx.requireFeature('C12');
  const id = uuid(record(await ctx.body()).id, 'id');
  const row = await centre.deps.store.table('curricula').get({ id, workspace_id: centre.access.workspace.id });
  if (!row) throw new SchoodAIError('not_found', 'Curriculum not found.', 404);
  if (!['generating', 'review', 'failed'].includes(row.status)) throw new SchoodAIError('curriculum_locked', 'This curriculum is already approved.', 409);
  const now = ctx.now();
  let units = await centre.deps.store.table('units').list({ curriculum_id: id });
  // A unit whose job stopped beating was interrupted (the function died): try it again.
  for (const unit of units.filter((u) => u.status === 'generating')) {
    const job = unit.generation_id ? await ctx.repo.generation(unit.generation_id) : null;
    const beat = job?.heartbeatAt ?? job?.updatedAt ?? unit.updated_at;
    if (now.getTime() - Date.parse(beat) > STALE_MS) await centre.deps.store.table('units').update({ id: unit.id, status: 'generating' }, { status: 'pending' });
  }
  units = await centre.deps.store.table('units').list({ curriculum_id: id });
  const next = units.filter((u) => u.status === 'pending' || u.status === 'changes_requested').sort((a, b) => a.position - b.position)[0];
  if (!next) {
    const status = units.every((u) => u.status === 'approved') ? 'approved' : units.some((u) => u.status === 'generating') ? 'generating' : 'review';
    const [updated] = await centre.deps.store.table('curricula').update({ id }, { status });
    return { curriculum: curriculumJson(updated, units), done: status !== 'generating' };
  }
  const [claimed] = await centre.deps.store.table('units').update({ id: next.id, status: next.status }, { status: 'generating', attempts: next.attempts + 1 });
  if (!claimed) return { curriculum: curriculumJson(row, units), done: false };
  const brief = briefOf(row);
  const job = await ctx.repo.createGeneration({ workspaceId: row.workspace_id, userId: ctx.user.id, feature: 'curriculum.unit', input: { curriculum_id: id, unit_id: next.id, position: next.position, level: next.level }, status: 'generating', heartbeatAt: now.toISOString() });
  await centre.deps.store.table('units').update({ id: next.id }, { generation_id: job.id });
  const previous = units.filter((u) => u.position < next.position && u.level === next.level).sort((a, b) => b.position - a.position).slice(0, 2).map((u) => u.title);
  const planned = asRecord(next.content).planned_can_do;
  try {
    const level = next.level as CefrLevel;
    const shape = { course: row.title, level, language: brief.language, lessons: brief.lessons_per_unit, minutes: brief.minutes, fallbackTitle: next.title };
    const { result, credits, chargeId } = await ctx.ai.charged({ key: 'curriculum.unit', mode: 'json', reference: `curriculum-unit:${next.id}:${next.attempts + 1}` }, async (session) => {
      const messages = [
        { role: 'system' as const, content: centrePrompt({
          workspace: centre.access.workspace, locale: ctx.locale,
          task: [
            unitTask({ track: brief.track, level, lessons: brief.lessons_per_unit, minutes: brief.minutes }),
            `Write teacher-facing text in ${LANGUAGE_NAMES[brief.language]}; English examples and test items in English. Original material only.`,
          ].join(' '),
          blocks: [{ kind: 'unit', title: 'This unit', data: { course: row.title, level: next.level, position: next.position, title: next.title, can_do: planned ?? [], previous_units: previous, reviewer_notes: next.review_notes } }],
        }) },
        { role: 'user' as const, content: 'Write the unit.' },
      ];
      let unit = unitFromDraft(await session.json({ messages, schema: unitDraftSchema, maxTokens: 4000, temperature: 0.4 }), shape);
      let problems = unitProblems(unit, brief.lessons_per_unit, brief.minutes);
      if (problems.length) {
        messages.push({ role: 'user' as const, content: `Fix these problems and reply with the whole unit again: ${problems.join(' ')}` });
        unit = unitFromDraft(await session.json({ messages, schema: unitDraftSchema, maxTokens: 4000, temperature: 0.2 }), shape);
        problems = unitProblems(unit, brief.lessons_per_unit, brief.minutes);
      }
      return { unit: { ...unit, problems }, problems };
    });
    await ctx.repo.updateGeneration(job.id, { status: 'ready', output: result.unit.material, verification: { problems: result.problems }, credits, chargeId, heartbeatAt: ctx.now().toISOString() }, ['generating']);
    await centre.deps.store.table('units').update({ id: next.id }, { status: 'ready', content: result.unit as unknown as Record<string, unknown>, title: result.unit.title });
  } catch (cause) {
    await ctx.repo.updateGeneration(job.id, { status: 'failed', errorCode: cause instanceof SchoodAIError ? cause.code.slice(0, 64) : 'internal_error' }, ['generating']);
    await centre.deps.store.table('units').update({ id: next.id }, { status: 'failed' });
    if (cause instanceof SchoodAIError && ['insufficient_credits', 'budget_exhausted', 'capped', 'ai_disabled', 'ai_unavailable'].includes(cause.code)) throw cause;
  }
  units = await centre.deps.store.table('units').list({ curriculum_id: id });
  const remaining = units.some((u) => u.status === 'pending' || u.status === 'changes_requested');
  const [updated] = await centre.deps.store.table('curricula').update({ id }, { status: remaining ? 'generating' : 'review' });
  return { curriculum: curriculumJson(updated, units), done: !remaining };
}

/** POST centre/curriculum-retry { unit_id }: puts a failed unit back in the queue. */
export async function retryUnit(ctx: RequestContext) {
  const centre = await requireCentre(ctx, ['owner', 'admin']);
  const [unit] = await centre.deps.store.table('units').update({ id: uuid(record(await ctx.body()).unit_id, 'unit_id'), workspace_id: centre.access.workspace.id, status: 'failed' }, { status: 'pending' });
  if (!unit) throw new SchoodAIError('not_found', 'No failed unit to retry.', 404);
  await centre.deps.store.table('curricula').update({ id: unit.curriculum_id }, { status: 'generating' });
  return { ok: true };
}

/** POST centre/curriculum-review { unit_id, decision: approve | changes, notes? }: the methodologist reviews each unit. */
export async function reviewUnit(ctx: RequestContext) {
  const centre = await requireCentre(ctx, STAFF_ROLES);
  const body = record(await ctx.body());
  const unit = await centre.deps.store.table('units').get({ id: uuid(body.unit_id, 'unit_id'), workspace_id: centre.access.workspace.id });
  if (!unit) throw new SchoodAIError('not_found', 'Unit not found.', 404);
  if (!['ready', 'approved', 'changes_requested'].includes(unit.status)) throw new SchoodAIError('not_ready', 'This unit is not ready for review.', 409, { status: unit.status });
  const decision = oneOf(body.decision, 'decision', ['approve', 'changes'] as const);
  const notes = optionalText(body.notes, 'notes', { max: 2000 });
  if (decision === 'changes' && !notes) throw new SchoodAIError('invalid_request', 'Say what should change.', 400, { field: 'notes' });
  const now = ctx.now().toISOString();
  await centre.deps.store.table('units').update({ id: unit.id }, decision === 'approve' ? { status: 'approved', reviewed_by: ctx.user.id, reviewed_at: now, review_notes: notes } : { status: 'changes_requested', reviewed_by: ctx.user.id, reviewed_at: now, review_notes: notes });
  if (unit.generation_id) await ctx.repo.updateGeneration(unit.generation_id, { status: decision === 'approve' ? 'approved' : 'rejected', decidedBy: ctx.user.id, decidedAt: now }, ['ready']);
  const units = await centre.deps.store.table('units').list({ curriculum_id: unit.curriculum_id });
  const status = units.every((u) => u.status === 'approved') ? 'approved' : decision === 'changes' ? 'generating' : 'review';
  const [row] = await centre.deps.store.table('curricula').update({ id: unit.curriculum_id }, { status, reviewer_id: ctx.user.id });
  await ctx.audit(`centre.curriculum_unit_${decision === 'approve' ? 'approved' : 'changes'}`, { position: unit.position }, { type: 'curriculum_unit', id: unit.id });
  return { curriculum: curriculumJson(row, units) };
}

/** POST centre/curriculum-publish { id, to_academy? }: saves every approved unit to the library; Academy Courses after Approve & run. */
export async function publish(ctx: RequestContext) {
  const centre = await requireCentre(ctx, ['owner', 'admin']);
  const body = record(await ctx.body());
  const row = await centre.deps.store.table('curricula').get({ id: uuid(body.id, 'id'), workspace_id: centre.access.workspace.id });
  if (!row) throw new SchoodAIError('not_found', 'Curriculum not found.', 404);
  const units = (await centre.deps.store.table('units').list({ curriculum_id: row.id })).sort((a, b) => a.position - b.position);
  if (!units.length || units.some((u) => u.status !== 'approved')) throw new SchoodAIError('not_approved', 'Every unit must be approved by the methodologist first.', 409);
  for (const unit of units) {
    if (unit.page_ids.length) continue;
    const content = unit.content as unknown as UnitContent;
    const page = await ctx.library.create({
      kind: 'note', title: `${row.title} · ${LEVEL_LABEL[unit.level as CefrLevel] ?? unit.level} · ${unit.position}. ${unit.title}`.slice(0, 200),
      body: unitMarkdown({ curriculum: row.title, level: unit.level, position: unit.position, unit: content }), folder: `Curricula/${row.title.replace(/\//g, '-').slice(0, 60)}/${LEVEL_LABEL[unit.level as CefrLevel] ?? unit.level}`,
      visibility: 'workspace', status: 'approved', sourceGenerationId: unit.generation_id,
    });
    await centre.deps.store.table('units').update({ id: unit.id }, { page_ids: [page.id] });
  }
  let actionId: string | null = null;
  if (body.to_academy === true) {
    if (!centre.access.workspace.academyTenantId) throw new SchoodAIError('academy_not_linked', 'This centre is not connected to Academy.', 409);
    const action = await ctx.actions.propose({ kind: 'centre_publish_course', payload: { curriculum_id: row.id, academy_id: centre.access.workspace.academyTenantId, title: row.title, units: units.length } });
    actionId = action.id;
  }
  const [updated] = await centre.deps.store.table('curricula').update({ id: row.id }, { status: 'published', published_at: ctx.now().toISOString(), ...(actionId ? { publish_action_id: actionId } : {}) });
  await ctx.audit('centre.curriculum_published', { units: units.length, to_academy: !!actionId }, { type: 'curriculum', id: row.id });
  return { curriculum: curriculumJson(updated, await centre.deps.store.table('units').list({ curriculum_id: row.id })), action_id: actionId };
}

interface PublishCourse { curriculum_id: string; academy_id: string; title: string; units: number }

export function registerCurriculumActions(): void {
  registerActionKind<PublishCourse>({
    kind: 'centre_publish_course',
    area: 'centre',
    approverRoles: ['owner', 'admin'],
    parse(value) {
      const p = record(value, 'payload');
      return { curriculum_id: uuid(p.curriculum_id, 'curriculum_id'), academy_id: uuid(p.academy_id, 'academy_id'), title: text(p.title, 'title', { max: 160 }), units: integer(p.units, 'units', 1, 200) };
    },
    summary: (p, locale) => pick(locale, { en: `Publish “${p.title}” to Academy Courses`, uz: `“${p.title}” kursini Academy’ga joylash`, ru: `Опубликовать «${p.title}» в курсах Academy` }),
    display: (p) => ({ course: p.title, units: String(p.units), where: 'Academy Courses: one course per level, a module per unit, a lesson per lesson, then published' }),
    async run(ctx, p) {
      const deps = await centreDeps(ctx);
      const row = await deps.store.table('curricula').get({ id: p.curriculum_id });
      if (!row) throw new SchoodAIError('not_found', 'The curriculum no longer exists.', 404);
      const client = academyClient(ctx, p.academy_id);
      const units = (await deps.store.table('units').list({ curriculum_id: row.id })).sort((a, b) => a.position - b.position);
      // Progress is kept so a retry continues instead of creating duplicates.
      const outline = asRecord(row.outline), done = { courses: {} as Record<string, string>, modules: {} as Record<string, string>, lessons: {} as Record<string, string>, published: {} as Record<string, boolean>, ...asRecord(outline.academy) };
      const save = () => deps.store.table('curricula').update({ id: row.id }, { outline: { ...outline, academy: done } });
      for (const level of [...new Set(units.map((u) => u.level))]) {
        if (!done.courses[level]) {
          const course = await client.post('upsert_course', { title: `${row.title} ${LEVEL_LABEL[level as CefrLevel] ?? level}`.slice(0, 160), level: LEVEL_LABEL[level as CefrLevel] ?? level, status: 'draft', description: `Made with Schood AI and reviewed by the centre (${units.filter((u) => u.level === level).length} units).` });
          done.courses[level] = String(asRecord(course.course).id ?? '');
          if (!done.courses[level]) throw new SchoodAIError('academy_unavailable', 'Academy did not return the course.', 502);
          await save();
        }
        let modulePosition = 0;
        for (const unit of units.filter((u) => u.level === level)) {
          modulePosition++;
          const content = unit.content as unknown as UnitContent;
          if (!done.modules[unit.id]) {
            const module = await client.post('upsert_module', { course_id: done.courses[level], title: `${modulePosition}. ${unit.title}`.slice(0, 160), position: modulePosition, description: content.can_do.join('; ').slice(0, 500) });
            done.modules[unit.id] = String(asRecord(module.module).id ?? '');
            await save();
          }
          for (const [index, lesson] of unitLessons(content).entries()) {
            const key = `${unit.id}:${index}`;
            if (done.lessons[key]) continue;
            const created = await client.post('upsert_lesson', { course_id: done.courses[level], module_id: done.modules[unit.id], title: lesson.title.slice(0, 160), summary: lesson.aims.join('; ').slice(0, 500), lesson_content: [{ type: 'rich_text', text: lessonMarkdown(lesson) }], position: index + 1, estimated_minutes: lesson.minutes });
            done.lessons[key] = String(asRecord(created.lesson).id ?? '');
            await save();
          }
        }
        if (!done.published[level]) { await client.post('publish_course', { course_id: done.courses[level] }); done.published[level] = true; await save(); }
      }
      return { courses: Object.keys(done.courses).length, lessons: Object.keys(done.lessons).length };
    },
    retrySafe: true,
    expiresInHours: 168,
  });
}

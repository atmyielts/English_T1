-- ============================================================================
-- Reliability telemetry: guardrail events (hard-delete blocks)
-- ============================================================================

create table if not exists public.guardrail_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  table_name text,
  row_id uuid,
  actor_user_id uuid references public.users(id) on delete set null,
  actor_role text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists guardrail_events_created_at_idx on public.guardrail_events (created_at desc);
create index if not exists guardrail_events_type_created_at_idx on public.guardrail_events (event_type, created_at desc);

alter table public.guardrail_events enable row level security;

drop policy if exists "Guardrail events view (admin only)" on public.guardrail_events;
create policy "Guardrail events view (admin only)"
on public.guardrail_events
for select
using (
  exists (select 1 from public.users u where u.id = auth.uid() and u.role = 'admin')
);

create or replace function public.prevent_catalog_hard_delete()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_allow_delete text;
  v_actor_id uuid;
  v_actor_role text;
begin
  v_allow_delete := current_setting('app.allow_hard_delete', true);
  if coalesce(v_allow_delete, '') = 'on' then
    return old;
  end if;

  begin
    v_actor_id := auth.uid();
  exception
    when others then v_actor_id := null;
  end;

  if v_actor_id is not null then
    begin
      select u.role into v_actor_role
      from public.users u
      where u.id = v_actor_id;
    exception
      when others then v_actor_role := null;
    end;
  end if;

  begin
    insert into public.guardrail_events (event_type, table_name, row_id, actor_user_id, actor_role, details)
    values (
      'hard_delete_blocked',
      tg_table_name,
      old.id,
      v_actor_id,
      v_actor_role,
      jsonb_build_object(
        'reason', 'hard_delete_blocked',
        'request_allow_hard_delete', coalesce(v_allow_delete, ''),
        'current_user', current_user
      )
    );
  exception
    when others then
      -- Keep the guardrail active even if telemetry insert fails.
      null;
  end;

  raise exception using
    errcode = 'P0001',
    message = format('Hard delete blocked for %s (%s)', tg_table_name, coalesce(old.id::text, 'unknown')),
    hint = case
      when tg_table_name = 'products' then 'Use status=''archived'' instead of DELETE.'
      when tg_table_name = 'plans' then 'Use is_active=false instead of DELETE.'
      else 'Use archive/deactivate workflow.'
    end;
end;
$$;
